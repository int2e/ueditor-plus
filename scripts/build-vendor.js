const esbuild = require('esbuild');
const path = require('node:path');
const fs = require('node:fs/promises');

async function buildVendor() {
    const result = await esbuild.build({
        entryPoints: [path.join(__dirname, '../_src/vendor/codemirror.js')],
        outfile: path.join(__dirname, '../third-party/codemirror/codemirror.js'),
        bundle: true,
        format: 'iife',
        globalName: 'UECodeMirror',
        target: 'es2018',
        minify: true,
        metafile: true,
        legalComments: 'eof',
        banner: {js: '/*! CodeMirror 6; generated by npm run build:vendor. See LICENSE.txt. */'}
    });
    const packages = new Set(Object.keys(result.metafile.inputs).map(input => {
        const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
        return match && match[1];
    }).filter(Boolean));
    const notices = [];
    for (const name of [...packages].sort()) {
        const dir = path.join(__dirname, '../node_modules', name);
        const pkg = JSON.parse(await fs.readFile(path.join(dir, 'package.json'), 'utf8'));
        const license = await fs.readFile(path.join(dir, 'LICENSE'), 'utf8');
        notices.push(`${name} ${pkg.version}\n\n${license}`);
    }
    await fs.writeFile(path.join(__dirname, '../third-party/codemirror/LICENSE.txt'), notices.join('\n\n---\n\n'));
}

module.exports = buildVendor;
if (require.main === module) buildVendor().catch(error => {
    console.error(error);
    process.exitCode = 1;
});
